//! LoMScenarioAddon output uses the official game's Lua API, never MortalModHost helpers.
use crate::{codegen::lua_str, project::Project};
use anyhow::{bail, ensure, Context, Result};
use serde_json::{json, Value};
use std::{collections::BTreeMap, fs, path::Path};

pub const TARGET: &str = "LoMScenarioAddon";
pub const SUPPORTED: &[&str] = &[
    "scene",
    "show",
    "hide",
    "move",
    "face",
    "focus",
    "say",
    "choice",
    "wait",
    "game_flag",
    "branch",
    "music",
    "sound",
    "intro",
    "end",
];
pub fn enabled(project: &Project) -> bool {
    project.manifest["target"] == TARGET
}
pub fn new_project(title: &str) -> Project {
    let mut p = Project::new();
    p.manifest = json!({"format":3,"package_format":3,"story_schema":2,"content_schema":1,
        "target":TARGET,"id":"my_story","name":title,"version":"0.1.0","author":"作者","entry":"main",
        "_editor":{"scenario_addon":{"id":"my_story","title":title,"version":"0.1.0","flags":[],"characters":[],
            "events":[{"id":"my_story_meet","position":"Back_Free_001","story":"main","rate":60,"once":true}]}}});
    p.stories.get_mut("main").unwrap()["title"] = json!(title);
    p.stories.get_mut("main").unwrap()["nodes"][0]["text"] = json!("ここから物語を書き始めます。");
    p
}
fn string<'a>(v: &'a Value, k: &str, default: &'a str) -> &'a str {
    v[k].as_str().unwrap_or(default)
}
fn q(v: &Value, k: &str, default: &str) -> String {
    lua_str(string(v, k, default))
}
fn number(v: &Value, k: &str, default: f64) -> String {
    v[k].as_f64().unwrap_or(default).to_string()
}
fn runtime_id(id: &str) -> bool {
    id.len() <= 64
        && id.as_bytes().first().is_some_and(u8::is_ascii_lowercase)
        && id
            .bytes()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == b'_')
}
fn fields(node: &Value, allowed: &[&str]) -> Result<()> {
    for (key, value) in node.as_object().context("ノードはオブジェクトが必要です")? {
        ensure!(
            ["id", "type", "goto", "_editor"].contains(&key.as_str())
                || allowed.contains(&key.as_str())
                || value.is_null(),
            "LoMScenarioAddon ではフィールド {key} に未対応です"
        );
    }
    for key in ["character", "view", "name", "flag"] {
        ensure!(
            !string(node, key, "").starts_with("user:"),
            "{key}: MortalModHost の user: 素材には未対応です"
        );
    }
    Ok(())
}

pub fn compile_story(story: &Value) -> Result<String> {
    ensure!(
        story.get("localization").is_none(),
        "章 {}: LoMScenarioAddon の書き出しでは多言語設定（localization）に未対応です。翻訳は制作データに保持されています",
        string(story, "id", "")
    );
    crate::validate::validate_story(story)?;
    let nodes = story["nodes"].as_array().context("nodes がありません")?;
    ensure!(!nodes.is_empty(), "章にノードがありません");
    // Table keys accept every editor node ID and avoid Lua's local-variable limit.
    let mut out =
        String::from("-- Generated by LoMScenarioKit for LoMScenarioAddon\nlocal nodes = {}\n");
    for (index, node) in nodes.iter().enumerate() {
        let id = string(node, "id", "");
        let result = (|| -> Result<String> {
            let kind = string(node,"type","");
            let next = node["goto"].as_str().or_else(|| nodes.get(index+1).and_then(|v| v["id"].as_str())).unwrap_or("");
            let jump = |target: &str| if target.is_empty() { "return nil".to_owned() } else { format!("return {}",lua_str(target)) };
            let c = q(node,"character","");
            let portrait = q(node,"portrait","normal");
            let mut code = String::new();
            let mut terminal = false;
            match kind {
                "scene" => {
                    fields(node,&["view"])?;
                    if string(node,"view","") == "out" { code.push_str("runblock(flowcharts.view, \"out\")\n"); }
                    else {
                        let view = q(node, "view", "");
                        if !["black", "white"].contains(&string(node, "view", "")) {
                            code.push_str(&format!("runwait(flowcharts.LoadView({view}))\n"));
                        }
                        code.push_str(&format!("getvar(flowcharts.view, \"ViewName\").value = {view}\nrunblock(flowcharts.view, \"view\")\n"));
                    }
                }
                "say" => {
                    fields(node,&["mode","character","portrait","text"])?;
                    let mode=string(node,"mode","character");
                    ensure!(["character","narrative","center"].contains(&mode), "台詞モード {mode} に未対応です");
                    code.push_str(&format!("setsaydialog(saydialogs.{mode})\n"));
                    if mode=="character" { code.push_str(&format!("runwait(characters.LoadCharacterAsset({c}))\ncharacters.LoadCharacterPortrait({c}, {portrait})\nstage.showPortrait(characters.Get({c}), characters.GetPortrait({c}, {portrait}))\ncharacters.Focus({c})\nsetcharacter(characters.Get({c}), characters.GetPortrait({c}, {portrait}))\n")); }
                    else { code.push_str("setcharacter(narrative)\n"); }
                    code.push_str(&format!("say({})\n",q(node,"text","")));
                }
                "show" | "hide" | "move" | "face" | "focus" => {
                    let allowed: &[&str] = match kind {
                        "show" => &["character","portrait","position","facing","fadeDuration","moveDuration"],
                        "hide" => &["character","fadeDuration"], "move" => &["character","from","to","duration"],
                        "face" => &["character","facing"], _ => &["character"] };
                    fields(node,allowed)?;
                    code.push_str(&format!("runwait(characters.LoadCharacterAsset({c}))\n"));
                    match kind {
                        "show" => { let pos=q(node,"position","M"); code.push_str(&format!("characters.LoadCharacterPortrait({c}, {portrait})\nstage.show{{character=characters.Get({c}), portrait=characters.GetPortrait({c}, {portrait}), fromPosition={pos}, toPosition={pos}, facing={}, fadeDuration={}, moveDuration={}, useDefaultSettings=false}}\n",q(node,"facing","right"),number(node,"fadeDuration",0.0),number(node,"moveDuration",0.0))); }
                        "hide" => code.push_str(&format!("stage.hide{{character=characters.Get({c}), fadeDuration={}, useDefaultSettings=false}}\n",number(node,"fadeDuration",0.0))),
                        "move" => code.push_str(&format!("stage.show{{character=characters.Get({c}), fromPosition={}, toPosition={}, moveDuration={}, useDefaultSettings=false}}\nwait({})\n",q(node,"from","M"),q(node,"to","M"),number(node,"duration",1.0),number(node,"duration",1.0))),
                        "face" => code.push_str(&format!("stage.show{{character=characters.Get({c}), facing={}, useDefaultSettings=false}}\n",q(node,"facing","right"))),
                        _ => code.push_str(&format!("characters.Focus({c})\n")),
                    }
                }
                "choice" => {
                    fields(node,&["dialog","options"])?;
                    ensure!(string(node,"dialog","Options")=="Options", "選択肢のダイアログは Options のみ対応しています");
                    let options=node["options"].as_array().context("options がありません")?;
                    let texts=options.iter().map(|o| q(o,"text","")).collect::<Vec<_>>().join(", ");
                    code.push_str(&format!("setmenudialog(menudialogs.Options)\nlocal choice = choose({{{texts}}})\nmenudialogs.Options.SetActive(false)\n"));
                    for (i,opt) in options.iter().enumerate() { ensure!(opt.as_object().is_some_and(|o| o.keys().all(|k| ["text","goto"].contains(&k.as_str()))), "選択肢の条件・追加属性には未対応です"); code.push_str(&format!("if choice == {} then {} end\n",i+1,jump(string(opt,"goto","")))); }
                }
                "wait" => { fields(node,&["seconds"])?; code.push_str(&format!("wait({})\n",number(node,"seconds",0.0))); }
                "game_flag" => { fields(node,&["flag","op","value"])?; let op=string(node,"op","set"); ensure!(["set","add"].contains(&op),"フラグ操作が不正です"); code.push_str(&format!("statmodifymanager.{}Flag({}, {})\n",if op=="add" {"Add"} else {"Set"},q(node,"flag",""),number(node,"value",0.0))); }
                "branch" => {
                    fields(node,&["source","flag","stat","cases"])?;
                    let source=string(node,"source","mod");
                    ensure!(["flag_value","condition"].contains(&source), "分岐元 {source} に未対応です。flag_value または condition を指定してください");
                    let flag=q(node,"flag","");
                    let expr=if source=="condition" {format!("(checkpointmanager.Condition({flag}) and 1 or 2)")} else {format!("tonumber(luamanager.GetFlagData({flag}))")};
                    code.push_str(&format!("local value = {expr}\n"));
                    for case in node["cases"].as_array().context("cases がありません")? {
                        let op=if source=="condition" {"=="} else {string(case,"op",">=")};
                        ensure!(["==","~=",">=","<=",">","<"].contains(&op), "比較演算子が不正です: {op}");
                        code.push_str(&format!("if value {op} {} then {} end\n",number(case,"value",0.0),jump(string(case,"goto",""))));
                    }
                }
                "music" | "sound" => {
                    fields(node,&["name","op","kind","seconds"])?;
                    let op=string(node,"op","play"); ensure!(["play","fadeout"].contains(&op),"音声操作に未対応です");
                    let method=if kind=="music" {if op=="play" {"PlayMusic"} else {"FadeOutMusic"}} else if op=="fadeout" {"FadeOutEnvSound"} else if string(node,"kind","sound")=="env" {"PlayEnvSound"} else {"PlaySound"};
                    let arg=if op=="play" {q(node,"name","")} else {number(node,"seconds",1.0)};
                    code.push_str(&format!("luamanager.{method}({arg})\n")); if op=="fadeout" {code.push_str(&format!("wait({arg})\n"));}
                }
                "intro" => {
                    fields(node,&["character","intro_source","title","name","text","image","image_scale","image_x","image_y"])?;
                    ensure!(string(node,"intro_source","official")=="official","Host用の紹介カードには未対応です");
                    for key in ["title","name","text","image"] {
                        ensure!(node[key].is_null() || node[key] == "", "紹介カードの独自フィールド {key} に未対応です");
                    }
                    for (key, default) in [("image_scale",100.0),("image_x",0.0),("image_y",0.0)] {
                        ensure!(node[key].is_null() || node[key].as_f64() == Some(default), "紹介カードの独自フィールド {key} に未対応です");
                    }
                    code.push_str(&format!("runwait(intropanel.Show({c}))\n"));
                }
                "end" => {
                    fields(node,&["next_script"])?;
                    if let Some(next)=node["next_script"].as_str().filter(|s| !s.is_empty()) { ensure!(runtime_id(next),"次の章のIDは英小文字・数字・_で指定してください"); code.push_str(&format!("luamanager.SetNextScript({})\nluamanager.Init()\n",lua_str(next))); }
                    else { code.push_str("runblock(flowcharts.view, \"out\")\nluamanager.ChangeScene(\"Free\", \"\", \"\")\n"); }
                    code.push_str("return nil\n"); terminal=true;
                }
                _ => bail!("LoMScenarioAddon ではノード種別 {kind} に未対応です"),
            }
            if !terminal {code.push_str(&format!("{}\n",jump(next)));}
            Ok(code)
        })().with_context(|| format!("章 {} / ノード {id}",string(story,"id","")))?;
        out.push_str(&format!(
            "nodes[{}] = function()\n{result}end\n",
            lua_str(id)
        ));
    }
    out.push_str(&format!(
        "local current = {}\nwhile current do\n current = nodes[current]()\nend\n",
        q(story, "start", "")
    ));
    Ok(out)
}

pub fn output(project: &Project) -> Result<BTreeMap<String, Vec<u8>>> {
    ensure!(
        enabled(project),
        "LoMScenarioAddon の制作プロジェクトを指定してください"
    );
    ensure!(
        project.assets.is_empty(),
        "Host形式の assets/ は変換できません。Addon素材は書き出し先に公式形式で追加してください"
    );
    let config = &project.manifest["_editor"]["scenario_addon"];
    ensure!(
        config.is_object() && !string(config, "id", "").is_empty(),
        "scenario_addon 設定と id が必要です"
    );
    let mut files = BTreeMap::new();
    for (id, story) in &project.stories {
        ensure!(
            runtime_id(id),
            "章ID {id}: 英小文字で始まる英小文字・数字・_（64文字以内）にしてください"
        );
        ensure!(story["id"] == *id, "章IDとキーが一致していません: {id}");
        for node in story["nodes"].as_array().into_iter().flatten() {
            if let Some(next) = node["next_script"].as_str().filter(|s| !s.is_empty()) {
                ensure!(
                    project.stories.contains_key(next),
                    "次の章 {next} がありません"
                );
            }
        }
        files.insert(
            format!("story/{id}.lua"),
            compile_story(story)?.into_bytes(),
        );
    }
    for section in ["events", "visits", "endings"] {
        if let Some(entries) = config.get(section) {
            for entry in entries
                .as_array()
                .with_context(|| format!("{section} は配列が必要です"))?
            {
                let story = string(entry, "story", "");
                ensure!(
                    project.stories.contains_key(story),
                    "{section} の参照先の章 {story} がありません"
                );
                ensure!(
                    runtime_id(string(entry, "id", "")),
                    "{section} の id が不正です"
                );
            }
        }
    }
    let language = string(config, "default_language", "ja");
    ensure!(
        !language.is_empty()
            && language.len() <= 32
            && language
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b == b'_' || b == b'-'),
        "default_language が不正です"
    );
    files.insert(format!("text.{language}.csv"), b"# key,text\n".to_vec());
    files.insert("scenario.json".into(), crate::stable_json(config)?);
    Ok(files)
}

/// Compile everything before touching the destination. Export only to a new folder.
pub fn export(project: &Project, target: &Path) -> Result<()> {
    let files = output(project)?;
    ensure!(
        !target.exists(),
        "書き出し先が存在します。新しいフォルダ名を指定してください"
    );
    let parent = target
        .parent()
        .filter(|p| !p.as_os_str().is_empty())
        .unwrap_or(Path::new("."));
    ensure!(parent.is_dir(), "書き出し先の親フォルダがありません");
    let temp = tempfile::tempdir_in(parent)?;
    for (path, bytes) in files {
        let file = temp.path().join(path);
        fs::create_dir_all(file.parent().unwrap())?;
        fs::write(file, bytes)?;
    }
    // create_dir reserves the target so another export can never replace an existing folder.
    fs::create_dir(target)?;
    for entry in fs::read_dir(temp.path())? {
        let entry = entry?;
        fs::rename(entry.path(), target.join(entry.file_name()))?;
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn localized_chapters_are_rejected_without_losing_catalogs_or_writing_output() {
        let mut project = new_project("多言語");
        for translations in [json!({}), json!({"cht":{"say1.text":"繁體台詞"}})] {
            project.stories.get_mut("main").unwrap()["localization"] = json!({
                "default_locale":"ja", "fallback_locale":"ja", "translations":translations
            });
            let story = &project.stories["main"];
            crate::validate::validate_story(story).unwrap();
            let original = story.clone();
            let error = compile_story(story).unwrap_err().to_string();
            assert!(error.contains("章 main"), "{error}");
            assert!(error.contains("localization"), "{error}");
            let temp = tempfile::tempdir().unwrap();
            let target = temp.path().join("scenario");
            assert!(export(&project, &target).is_err());
            assert!(!target.exists());
            assert_eq!(project.stories["main"], original);
        }
    }

    #[test]
    fn character_speech_updates_the_stage_expression_and_solid_views_need_no_asset() {
        let mut project = new_project("表情");
        let story = project.stories.get_mut("main").unwrap();
        story["nodes"] = json!([
            {"id":"say1","type":"show","character":"artist1","portrait":"normal","position":"M"},
            {"id":"talk","type":"say","character":"artist1","portrait":"normal","text":"表情を更新する"},
            {"id":"black","type":"scene","view":"black"},
            {"id":"white","type":"scene","view":"white"},
            {"id":"end1","type":"end"}
        ]);
        let lua = compile_story(story).unwrap();
        let talk = lua
            .split("nodes[\"talk\"] = function()")
            .nth(1)
            .unwrap()
            .split("nodes[\"black\"]")
            .next()
            .unwrap();
        assert!(talk.contains("stage.showPortrait(characters.Get(\"artist1\"), characters.GetPortrait(\"artist1\", \"normal\"))"));
        assert!(!lua.contains("LoadView(\"black\")"));
        assert!(!lua.contains("LoadView(\"white\")"));
        assert!(lua.contains(".value = \"black\""));
        story["nodes"][1]["voice"] = json!("user:voice");
        assert!(compile_story(story).is_err());
    }
    #[test]
    fn native_project_exports_official_lua_and_refuses_host_nodes_without_partial_output() {
        let mut project = new_project("テスト");
        let files = output(&project).unwrap();
        let lua = String::from_utf8(files["story/main.lua"].clone()).unwrap();
        assert!(lua.contains("say(\"ここから物語"));
        assert!(!lua.contains("mod_"));
        let temp = tempfile::tempdir().unwrap();
        let target = temp.path().join("scenario");
        project.stories.get_mut("main").unwrap()["nodes"][0] =
            crate::story_api::new_node("background", "say1").unwrap();
        assert!(export(&project, &target).is_err());
        assert!(!target.exists());
    }
}
